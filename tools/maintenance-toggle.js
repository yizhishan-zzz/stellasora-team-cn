/**
 * maintenance-toggle.js —— 开关站点维护页
 *
 * 用法：node tools/maintenance-toggle.js on|off
 *
 * on  ：把 _redirects 里的规则打开，所有页面都会跳到 maintenance.html
 * off ：把规则注释掉，网站恢复正常访问
 *
 * 改完需要发布（推送到线上.bat）才会生效。
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');

const mode = String(process.argv[2] || '').toLowerCase();
if (mode !== 'on' && mode !== 'off') {
  console.log('用法: node tools/maintenance-toggle.js on|off');
  process.exit(1);
}

const PAGES = [
  '/', '/index.html',
  '/characters', '/characters.html',
  '/patterns', '/patterns.html',
  '/teams', '/teams.html',
  '/updates', '/updates.html',
  '/character', '/character.html',
  '/pattern', '/pattern.html',
  '/team', '/team.html'
];

if (mode === 'on' && !fs.existsSync(path.join(ROOT, 'maintenance.html'))) {
  console.log('[X] maintenance.html 不存在，无法开启维护模式');
  process.exit(1);
}

const head = [
  '# ===== maintenance switch =====',
  '# generated by tools/maintenance-toggle.js - do not edit by hand',
  '# state: ' + (mode === 'on' ? 'ON (every page shows the maintenance page)' : 'OFF (site works normally)'),
  ''
];
const lines = PAGES.map(p => (mode === 'on' ? '' : '# ') + p + '  /maintenance.html  200');
const body = head.concat(lines).join('\n') + '\n';

fs.writeFileSync(path.join(ROOT, '_redirects'), body, 'utf8');
console.log('');
console.log(mode === 'on'
  ? '[维护模式] 已开启：所有页面会跳到 maintenance.html'
  : '[维护模式] 已关闭：网站恢复正常访问');
console.log('  _redirects 已更新（' + PAGES.length + ' 条规则）');
console.log('');
console.log('  要让线上生效，还需要发布：双击 tools\\推送到线上.bat');